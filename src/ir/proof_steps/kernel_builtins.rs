//! The proof kernel's table of builtin signatures (`Kernel.Builtins`,
//! `tools/proof-kernel/kernel/builtins.av`), generated from the type
//! checker's own registrations so the kernel carries no second, hand-written
//! list: `aver kernel-builtins` prints it, and
//! `tools/regenerate_proof_kernel.py` installs it.
//!
//! Beside the signatures the table says which type shapes carry an `==`
//! that is equality once their parts do
//! ([`crate::ir::SymbolTable::beq_is_equality`], the condition Lean's model
//! proves); a declared type says the same in its own declaration in each
//! script (`eq`, written by `sexpr`). Widening that set is a change to that
//! one function and a regeneration, not to the kernel.
//!
//! A signature with a function-typed parameter is left out: no step term
//! applies such a builtin. The intrinsics a step term may name and the empty
//! map literal are typed here as `crate::ir::proof_steps::term` types them.

use crate::ast::Type;

/// The Aver source of the `Kernel.Builtins` module.
pub fn aver_source() -> String {
    let mut rows: Vec<(String, Vec<Type>, Type)> = crate::types::checker::builtin_signatures()
        .into_iter()
        .filter(|(_, params, ret)| !params.iter().chain([ret]).any(has_fn))
        .collect();
    let t = || Type::Var("T".into());
    rows.push((
        "Map.empty".into(),
        vec![],
        Type::Map(
            Box::new(Type::Var("K".into())),
            Box::new(Type::Var("V".into())),
        ),
    ));
    for name in [
        "__int_div_euclid",
        "__int_mod_euclid",
        "__bits_shl",
        "__bits_shr",
    ] {
        rows.push((name.into(), vec![Type::Int, Type::Int], Type::Int));
    }
    rows.push(("__bits_low".into(), vec![Type::Int, Type::Int], Type::Int));
    rows.push((
        "__bits_popcount".into(),
        vec![Type::Int, Type::Int],
        Type::Int,
    ));
    rows.push((
        "__vector_new".into(),
        vec![Type::Int, t()],
        Type::Vector(Box::new(t())),
    ));
    rows.push(("__to_str".into(), vec![t()], Type::Str));
    rows.sort_by(|a, b| a.0.cmp(&b.0));
    rows.dedup_by(|a, b| a.0 == b.0);
    let mut out = String::from(
        "module Builtins\n    intent =\n        \"The signature of every builtin a step term may apply. GENERATED by `aver kernel-builtins`\"\n        \"from the compiler's type checker (src/types/checker/builtins.rs); do not edit by hand.\"\n        \"A type variable is bound by the arguments, in order, and the result is read at that binding.\"\n    exposes [Sig, sig, equality]\n    depends [Kernel.Term]\n    effects []\n\nrecord Sig\n    params: List<Ty>\n    ret: Ty\n\nfn sig(name: String) -> Option<Sig>\n    ? \"The signature of a builtin, by its dotted name.\"\n    match name\n",
    );
    for (name, params, ret) in &rows {
        let ps: Vec<String> = params.iter().map(ty).collect();
        out.push_str(&format!(
            "        \"{name}\" -> Option.Some(Sig(params = [{}], ret = {}))\n",
            ps.join(", "),
            ty(ret)
        ));
    }
    out.push_str("        _ -> Option.None\n\nverify sig\n    sig(\"List.len\") => Option.Some(Sig(params = [Ty.TyList(Ty.TyVar(\"T\", false))], ret = Ty.TyInt))\n    sig(\"List.map\") => Option.None\n");
    out.push_str("\nfn equality(shape: String) -> Bool\n    ? \"Whether == between two values of a type of this shape is equality once it is for the shape's parts: the shapes Lean's model proves it for. A hole, the type of no value, has one.\"\n    match shape\n");
    let symbols = crate::ir::SymbolTable::default();
    let int = || Box::new(Type::Int);
    let shapes: [(&str, Type); 11] = [
        ("Int", Type::Int),
        ("Bool", Type::Bool),
        ("String", Type::Str),
        ("Unit", Type::Unit),
        ("Float", Type::Float),
        ("List", Type::List(int())),
        ("Option", Type::Option(int())),
        ("Result", Type::Result(int(), int())),
        ("tuple", Type::Tuple(vec![Type::Int, Type::Int])),
        ("Map", Type::Map(int(), int())),
        ("Vector", Type::Vector(int())),
    ];
    for (shape, probe) in &shapes {
        if symbols.beq_is_equality(probe) {
            out.push_str(&format!("        \"{shape}\" -> true\n"));
        }
    }
    out.push_str("        \"_\" -> true\n        _ -> false\n\nverify equality\n    equality(\"Int\") => true\n    equality(\"Float\") => false\n");
    out
}

fn has_fn(t: &Type) -> bool {
    match t {
        Type::Fn(..) | Type::Invalid => true,
        Type::List(a) | Type::Option(a) | Type::Vector(a) => has_fn(a),
        Type::Result(a, b) | Type::Map(a, b) => has_fn(a) || has_fn(b),
        Type::Tuple(xs) => xs.iter().any(has_fn),
        _ => false,
    }
}

fn ty(t: &Type) -> String {
    match t {
        Type::Int => "Ty.TyInt".into(),
        Type::Float => "Ty.TyFloat".into(),
        Type::Str => "Ty.TyStr".into(),
        Type::Bool => "Ty.TyBool".into(),
        Type::Unit => "Ty.TyUnit".into(),
        Type::List(a) => format!("Ty.TyList({})", ty(a)),
        Type::Option(a) => format!("Ty.TyOption({})", ty(a)),
        Type::Vector(a) => format!("Ty.TyVector({})", ty(a)),
        Type::Result(a, b) => format!("Ty.TyResult({}, {})", ty(a), ty(b)),
        Type::Map(k, v) => format!("Ty.TyMap({}, {})", ty(k), ty(v)),
        Type::Tuple(xs) => format!(
            "Ty.TyTuple([{}])",
            xs.iter().map(ty).collect::<Vec<_>>().join(", ")
        ),
        Type::Var(n) => format!("Ty.TyVar(\"{n}\", false)"),
        Type::Named { name, .. } => format!("Ty.TyNamed(\"{name}\")"),
        Type::Fn(..) | Type::Invalid => "Ty.TyAny".into(),
    }
}
