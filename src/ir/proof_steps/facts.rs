/// A fact about vectors: each given with what it ranges over; `when` is
/// the law's own premise, proved by `Hyp("when")`.
fn vector_fact(
    key: &'static str,
    lean: &'static str,
    sorts: &[(&str, Sort)],
    premise: Option<Term>,
    eq: (Term, Term),
    proof: Proof,
    uses: &[Fact],
) -> Fact {
    let givens: Vec<String> = sorts.iter().map(|(g, _)| g.to_string()).collect();
    Fact {
        key,
        lean,
        sorts: sorts.iter().map(|(g, s)| (g.to_string(), *s)).collect(),
        script: Script {
            obligation: Obligation {
                key: key.to_string(),
                givens,
                types: sorts
                    .iter()
                    .map(|(g, s)| (g.to_string(), sort_type(*s)))
                    .collect(),
                finite: Vec::new(),
                lists: sorts
                    .iter()
                    .filter(|(_, s)| matches!(s, Sort::List | Sort::EqList))
                    .map(|(g, _)| g.to_string())
                    .collect(),
                ints: Vec::new(),
                premise,
                refined: Vec::new(),
                lhs: eq.0,
                rhs: eq.1,
            },
            defs: Vec::new(),
            consts: Vec::new(),
            laws: uses.iter().map(Fact::law_ref).collect(),
            decls: Default::default(),
            sigs: Vec::new(),
            plan: None,
            proof,
        },
    }
}

