/// `List.concat(List.take(l, n), List.drop(l, n)) = l`, by induction on
/// `l` for every `n`: a cell splits on `n <= 0`, and above zero the tail
/// is split at `n - 1`.
fn concat_take_drop() -> Fact {
    let (l, n, x, t) = (|| var("l"), || var("n"), || var("x"), || var("t"));
    let nil = term::nil;
    let less = || binop(BinOp::Sub, n(), one());
    let xt = || cell(x(), t());
    let split = |l: Term, n: Term| concat(take(l.clone(), n.clone()), drop(l, n));
    let base = trans(
        vec![
            split(nil(), n()),
            concat(nil(), drop(nil(), n())),
            concat(nil(), nil()),
            nil(),
        ],
        vec![
            congr(
                concat(term::hole(), drop(nil(), n())),
                rule(WallRule::TakeNil, vec![("n", n())]),
            ),
            congr(
                concat(nil(), term::hole()),
                rule(WallRule::DropNil, vec![("n", n())]),
            ),
            rule(WallRule::ConcatNil, vec![("b", nil())]),
        ],
    );
    let at_most_zero = trans(
        vec![
            split(xt(), n()),
            concat(nil(), drop(xt(), n())),
            concat(nil(), xt()),
            xt(),
        ],
        vec![
            congr(
                concat(term::hole(), drop(xt(), n())),
                counted_cell(WallRule::TakeConsLe, x(), t(), n(), "h_le", false),
            ),
            congr(
                concat(nil(), term::hole()),
                counted_cell(WallRule::DropConsLe, x(), t(), n(), "h_le", false),
            ),
            rule(WallRule::ConcatNil, vec![("b", xt())]),
        ],
    );
    let above_zero = trans(
        vec![
            split(xt(), n()),
            concat(cell(x(), take(t(), less())), drop(xt(), n())),
            concat(cell(x(), take(t(), less())), drop(t(), less())),
            cell(x(), split(t(), less())),
            xt(),
        ],
        vec![
            congr(
                concat(term::hole(), drop(xt(), n())),
                counted_cell(WallRule::TakeConsGt, x(), t(), n(), "h_le", true),
            ),
            congr(
                concat(cell(x(), take(t(), less())), term::hole()),
                counted_cell(WallRule::DropConsGt, x(), t(), n(), "h_le", true),
            ),
            rule(
                WallRule::ConcatCons,
                vec![
                    ("x", x()),
                    ("a", take(t(), less())),
                    ("b", drop(t(), less())),
                ],
            ),
            congr(cell(x(), term::hole()), Proof::Hyp("ih".into())),
        ],
    );
    vector_fact(
        "List.concat.takeDrop",
        "list_concat_takeDrop",
        &[("l", Sort::List), ("n", Sort::Int)],
        None,
        (split(l(), n()), l()),
        Proof::InductList {
            var: "l".into(),
            carried: Vec::new(),
            lhs: split(l(), n()),
            rhs: l(),
            nil: Box::new(base),
            head: "x".into(),
            tail: "t".into(),
            general: vec!["n".into()],
            ihs: vec![super::IhAt {
                name: "ih".into(),
                at: vec![less()],
                carry: Vec::new(),
            }],
            cons: Box::new(Proof::Cases {
                on: binop(BinOp::Lte, n(), zero()),
                hyp: "h_le".into(),
                if_true: Box::new(at_most_zero),
                if_false: Box::new(above_zero),
            }),
        },
        &[],
    )
}

/// `List.len(List.drop(l, n)) <= List.len(l)`, by induction on `l` for
/// every `n`.
fn len_of_drop_at_most() -> Fact {
    let (l, n, x, t) = (|| var("l"), || var("n"), || var("x"), || var("t"));
    let nil = term::nil;
    let less = || binop(BinOp::Sub, n(), one());
    let xt = || cell(x(), t());
    let at_most = |l: Term, n: Term| binop(BinOp::Lte, len(drop(l.clone(), n)), len(l));
    let base = trans(
        vec![
            at_most(nil(), n()),
            binop(BinOp::Lte, len(nil()), len(nil())),
            binop(BinOp::Lte, zero(), len(nil())),
            binop(BinOp::Lte, zero(), zero()),
            term::boolean(true),
        ],
        vec![
            congr(
                binop(BinOp::Lte, len(term::hole()), len(nil())),
                rule(WallRule::DropNil, vec![("n", n())]),
            ),
            congr(binop(BinOp::Lte, term::hole(), len(nil())), len_nil()),
            congr(binop(BinOp::Lte, zero(), term::hole()), len_nil()),
            Proof::Compute {
                lhs: binop(BinOp::Lte, zero(), zero()),
                rhs: term::boolean(true),
            },
        ],
    );
    let same = binop(BinOp::Lte, len(xt()), len(xt()));
    let at_most_zero = trans(
        vec![at_most(xt(), n()), same.clone(), term::boolean(true)],
        vec![
            congr(
                binop(BinOp::Lte, len(term::hole()), len(xt())),
                counted_cell(WallRule::DropConsLe, x(), t(), n(), "h_le", false),
            ),
            linear_from(same, &[]),
        ],
    );
    let shorter = binop(BinOp::Lte, len(drop(t(), less())), add(len(t()), one()));
    let above_zero = trans(
        vec![
            at_most(xt(), n()),
            binop(BinOp::Lte, len(drop(t(), less())), len(xt())),
            shorter.clone(),
            term::boolean(true),
        ],
        vec![
            congr(
                binop(BinOp::Lte, len(term::hole()), len(xt())),
                counted_cell(WallRule::DropConsGt, x(), t(), n(), "h_le", true),
            ),
            congr(
                binop(BinOp::Lte, len(drop(t(), less())), term::hole()),
                rule(WallRule::LenCons, vec![("x", x()), ("a", t())]),
            ),
            linear_from(shorter, &[("ih", at_most(t(), less()), true)]),
        ],
    );
    vector_fact(
        "List.len.ofDropAtMost",
        "list_len_ofDropAtMost",
        &[("l", Sort::List), ("n", Sort::Int)],
        None,
        (at_most(l(), n()), term::boolean(true)),
        Proof::InductList {
            var: "l".into(),
            carried: Vec::new(),
            lhs: at_most(l(), n()),
            rhs: term::boolean(true),
            nil: Box::new(base),
            head: "x".into(),
            tail: "t".into(),
            general: vec!["n".into()],
            ihs: vec![super::IhAt {
                name: "ih".into(),
                at: vec![less()],
                carry: Vec::new(),
            }],
            cons: Box::new(Proof::Cases {
                on: binop(BinOp::Lte, n(), zero()),
                hyp: "h_le".into(),
                if_true: Box::new(at_most_zero),
                if_false: Box::new(above_zero),
            }),
        },
        &[],
    )
}

