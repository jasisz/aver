//! Facts about the builtins: equations stated directly over builtin calls
//! with untyped variables, each proved by steps from the wall rules.
//!
//! A law cites a fact by its key in `using` (`List.concat.assoc`), like a
//! law of its own program. A citation carries the fact's whole step proof
//! ([`super::LawRef::fact`]), and the kernel checks that proof before it
//! lets a step use the fact, so a fact is never an assumption. Lean
//! states each fact once, for every element type (`{α : Type}`), from the
//! same terms, and proves it with the same steps.
//!
//! The `List.` prefix of a `using` name is reserved for these facts: a
//! user module named `List` is already refused.

use crate::ast::{BinOp, Type};

use super::term::{self, Term, binop, builtin, var};
use super::{LawRef, Obligation, Proof, Script, WallRule};

/// What a given of a fact ranges over. A fact holds for every element,
/// key and value type, so a given has no Aver type, only this.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Sort {
    /// A list of any element type.
    List,
    /// A map of any key and value types.
    Map,
    /// A key of that map.
    Key,
    /// A value of that map.
    Value,
    /// A vector of any element type.
    Vector,
    /// An element of that vector (or list).
    Elem,
    /// An Int, such as an index.
    Int,
    /// A list whose element type has a `==` that is equality (no Float
    /// inside), the only lists `List.contains` finds an element in front
    /// of by its rule.
    EqList,
    /// An element of such a list.
    EqElem,
}

/// The type variable a fact's map keys have: one whose `==` must be
/// equality, which the data marks (`sexpr::ty_text`).
pub(crate) const KEY_TYPE_VAR: &str = "K";

/// The type a fact's given is written with: a list, map or vector over
/// type variables, a type variable, or an Int. A fact holds at every type
/// of each variable; its own proof sees each as one unknown type.
fn sort_type(s: Sort) -> crate::ast::Type {
    use crate::ast::Type;
    let var = |n: &str| Type::Var(n.to_string());
    match s {
        Sort::List => Type::List(Box::new(var("T"))),
        Sort::Map => Type::Map(Box::new(var(KEY_TYPE_VAR)), Box::new(var("V"))),
        Sort::Key => var(KEY_TYPE_VAR),
        Sort::Value => var("V"),
        Sort::Vector => Type::Vector(Box::new(var("T"))),
        Sort::Elem => var("T"),
        Sort::Int => Type::Int,
        Sort::EqList => Type::List(Box::new(var(KEY_TYPE_VAR))),
        Sort::EqElem => var(KEY_TYPE_VAR),
    }
}

/// One fact: its key in `using`, its Lean theorem name, what each given
/// ranges over, and its script.
#[derive(Debug, Clone, PartialEq)]
pub struct Fact {
    pub key: &'static str,
    pub lean: &'static str,
    pub sorts: Vec<(String, Sort)>,
    pub script: Script,
}

impl Fact {
    /// The fact as a law a script cites, with its proof.
    pub fn law_ref(&self) -> LawRef {
        let ob = &self.script.obligation;
        LawRef {
            key: self.key.to_string(),
            givens: ob.givens.clone(),
            types: ob.types.clone(),
            premise: ob.premise.clone(),
            refined: Vec::new(),
            lhs: ob.lhs.clone(),
            rhs: ob.rhs.clone(),
            fact: Some(Box::new(self.script.clone())),
        }
    }
}

impl Fact {
    /// The statement as an Aver law claim: `lhs => rhs`.
    pub fn claim(&self) -> String {
        let ob = &self.script.obligation;
        let show = |t: &Term| super::show::term(t, &super::sexpr::BuiltinsOnly);
        format!("{} => {}", show(&ob.lhs), show(&ob.rhs))
    }

    /// The facts its proof cites.
    pub fn cites(&self) -> Vec<String> {
        self.script.laws.iter().map(|l| l.key.clone()).collect()
    }

    /// Its `when`, written as Aver, if it has one.
    pub fn when(&self) -> Option<String> {
        let show = |t: &Term| super::show::term(t, &super::sexpr::BuiltinsOnly);
        self.script.obligation.premise.as_ref().map(show)
    }

    /// Whether every given is a list.
    pub fn over_lists(&self) -> bool {
        self.sorts.iter().all(|(_, s)| *s == Sort::List)
    }
}

/// The facts whose key starts with `prefix`, as Markdown: one entry per
/// fact with its statement as an Aver law. `docs/builtin-facts.md` is this
/// text for every fact.
pub fn markdown(prefix: &str) -> String {
    let mut out = String::from(
        "# Builtin facts\n\n<!-- Generated by `aver facts --markdown > docs/builtin-facts.md`; edit `src/ir/proof_steps/facts.rs`, not this file. -->\n\nA law cites a builtin fact by name in `using`, as it cites a law of its own program. Each fact holds for lists and vectors of every element type (a `List.contains` fact, of every element type whose `==` is equality, so no Float inside), and for maps of every key and value type, so its givens have no type here: `a`, `b`, `c` and `l` are lists, `y` the value `List.contains` looks for, `n` an Int count, `m` a map, `k` and `k2` its keys and `v` its value; in a `Vector.` fact `v` is a vector, `i` and `j` are indices and `x` an element. The proof of each fact is written as steps and travels with every citation: the kernel written in Aver checks it before the law may use the fact, and Lean states the fact once, for every element type, and proves it with the same steps. When the steps stop at a term a fact's left side matches, `aver proof` names the fact in a hint. `aver facts` prints this list.\n",
    );
    for fact in all().iter().filter(|f| f.key.starts_with(prefix)) {
        let when = fact
            .when()
            .map(|w| format!("when {w}\n"))
            .unwrap_or_default();
        out.push_str(&format!(
            "\n## `{}`\n\n```aver\ngiven {}\n{when}{}\n```\n",
            fact.key,
            fact.script.obligation.givens.join(", "),
            fact.claim()
        ));
        let cites = fact.cites();
        if !cites.is_empty() {
            out.push_str(&format!(
                "\nProved from {}.\n",
                cites
                    .iter()
                    .map(|c| format!("`{c}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
    }
    out
}

/// Whether `name` is in the namespace reserved for facts.
pub fn is_fact_name(name: &str) -> bool {
    name.starts_with("List.") || name.starts_with("Map.") || name.starts_with("Vector.")
}

pub fn named(key: &str) -> Option<Fact> {
    BUILT.with(|all| all.iter().find(|f| f.key == key).cloned())
}

/// The facts the step producer rewrites with where evaluation stops,
/// whether or not a law cites them: the list facts, each read left to
/// right. Every one turns its left side into a smaller term in the
/// lexicographic path order whose precedence puts `List.len` and
/// `List.contains` above `List.reverse`, `List.take` and `List.drop`,
/// those above `List.concat`, and that above `List.prepend`, `Bool.or`,
/// `+` and the literals: a rewrite either drops part of the term
/// (`List.concat(a, []) => a`), moves a higher builtin below a lower one
/// (`List.reverse` below `List.concat`, `List.len` below `+`,
/// `List.contains` below `Bool.or`), reassociates `List.concat` to the
/// right, or decides an equality to a Bool (`List.prepend(x, t) == []` is
/// `false`). The
/// list rules evaluation itself steps by decrease in the same order, so
/// rewriting with these facts and those rules always reaches a normal form;
/// the producer's fuel and its check that a rewrite never comes back to an
/// earlier term bound it besides. A fact with a `when` applies only where
/// its `when` is proved. The `Map.` and `Vector.` facts are left out:
/// evaluation already steps by their rules, and `Vector.len.asList`
/// would grow the term.
pub const NORMALIZING: &[&str] = &[
    "List.len.ofConcat",
    "List.concat.assoc",
    "List.concat.rightIdentity",
    "List.len.nonneg",
    "List.take.ofConcat",
    "List.drop.ofConcat",
    "List.take.nonPositive",
    "List.drop.nonPositive",
    "List.concat.takeDrop",
    "List.len.ofDropAtMost",
    "List.len.ofReverse",
    "List.reverse.ofConcat",
    "List.reverse.involutive",
    "List.contains.ofConcat",
    "List.contains.ofReverse",
    "List.prepend.notEmpty",
    "List.prepend.notEmptySwapped",
    "List.concat.notEmpty",
    "List.concat.notEmptySwapped",
];

/// The facts of [`NORMALIZING`], in the order [`all`] lists them.
pub fn normalizing() -> Vec<Fact> {
    BUILT.with(|all| {
        all.iter()
            .filter(|f| NORMALIZING.contains(&f.key))
            .cloned()
            .collect()
    })
}

