//! Unicode case-mapping tables for the wasm-gc `String.toLower` /
//! `String.toUpper` helpers, plus the passive-data-segment blob the
//! helpers read them from.
//!
//! # Where the numbers come from
//!
//! Every table below is DERIVED FROM RUST'S OWN `char::to_lowercase`
//! / `char::to_uppercase` by probing all 1 112 064 Unicode scalars —
//! no new dependency, and the wasm-gc backend maps exactly what the VM
//! (`src/types/string.rs`) and the generated Rust
//! (`src/codegen/rust/from_mir.rs`) map. The two context predicates the
//! final-sigma rule needs are probed the same way, through
//! `str::to_lowercase` itself:
//!
//! ```text
//! cased(c)      := format!("{c}Σ").to_lowercase().ends_with('ς')
//! ignorable(c)  := !cased(c) && format!("a{c}Σ").to_lowercase().ends_with('ς')
//! ```
//!
//! These deliberately return the EFFECTIVE predicates in the order
//! `str::to_lowercase` applies them (`skip_while(Case_Ignorable).next()
//! .map(Cased)`): a scalar that Unicode marks both Cased and
//! Case_Ignorable — modifier letters such as U+02B0 — comes out of the
//! probes as ignorable-only, which is what the helper must implement.
//! The two sets are therefore disjoint by construction.
//!
//! # Regenerating
//!
//! The constants are committed, and `case_tables_match_std` re-derives
//! them from std on every test run — so a toolchain whose Unicode
//! version moved turns that test red instead of silently shipping stale
//! mappings. To refresh:
//!
//! ```text
//! cargo test -p aver-lang --lib --features wasm,wasip2 \
//!     dump_case_tables -- --ignored --nocapture
//! ```
//!
//! and paste the printed constants over the ones below.

/// One run of scalars that all shift by the same amount:
/// `(first, last, delta)`, sorted by `first`, disjoint.
pub(in crate::codegen::wasm_gc) type SimpleRun = (u32, u32, i32);

/// One scalar whose case mapping is longer than a single scalar:
/// `(from, [to0, to1, to2])`, with `to2 == 0` meaning "two scalars".
pub(in crate::codegen::wasm_gc) type Expansion = (u32, [u32; 3]);

/// An inclusive scalar range, sorted and disjoint.
pub(in crate::codegen::wasm_gc) type Range = (u32, u32);

/// Largest ratio of output UTF-8 bytes to input UTF-8 bytes over all
/// scalars, rounded up — the over-allocation factor `String.toLower`
/// uses for its output buffer.
pub(in crate::codegen::wasm_gc) const MAX_LOWER_GROWTH: u32 = 2;

/// Same for `String.toUpper`. U+0390 and U+03B0 are the worst case:
/// one 2-byte scalar becomes three 2-byte scalars.
pub(in crate::codegen::wasm_gc) const MAX_UPPER_GROWTH: u32 = 3;

